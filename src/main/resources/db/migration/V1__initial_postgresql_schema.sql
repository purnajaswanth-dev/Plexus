-- 1. Repositories
CREATE TABLE IF NOT EXISTS repositories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_name VARCHAR(255) NOT NULL,
    repo_url VARCHAR(255),
    default_branch VARCHAR(255),
    description TEXT,
    language VARCHAR(255),
    last_indexed TIMESTAMP WITHOUT TIME ZONE,
    index_status VARCHAR(255),
    dependency_file_type VARCHAR(255),
    added_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
    commit_sha VARCHAR(255),
    status_detail TEXT,
    is_monorepo BOOLEAN DEFAULT FALSE,
    total_files_discovered INT
);

-- 2. Repository Dependencies
CREATE TABLE IF NOT EXISTS repo_dependencies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "repoId" BIGINT NOT NULL,
    group_id VARCHAR(255),
    artifact_id VARCHAR(255),
    version VARCHAR(255),
    scope VARCHAR(255),
    is_dev BOOLEAN DEFAULT FALSE,
    package_type VARCHAR(255),
    manifest_path VARCHAR(255),
    CONSTRAINT fk_repo_dependencies_repo FOREIGN KEY ("repoId") REFERENCES repositories(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_repo_dep_repoid ON repo_dependencies("repoId");
CREATE INDEX IF NOT EXISTS idx_repo_dep_artifact ON repo_dependencies(artifact_id);
CREATE INDEX IF NOT EXISTS idx_repo_dep_artifact_group ON repo_dependencies(artifact_id, group_id);

-- 3. Architecture Snapshots
CREATE TABLE IF NOT EXISTS architecture_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id BIGINT NOT NULL,
    commit_sha VARCHAR(255),
    analyzed_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
    status VARCHAR(255),
    primary_language VARCHAR(255),
    total_files_analyzed INT,
    total_components INT,
    total_relationships INT,
    analysis_summary TEXT,
    CONSTRAINT fk_snapshot_repo FOREIGN KEY (repo_id) REFERENCES repositories(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_snapshot_repo ON architecture_snapshots(repo_id);
CREATE INDEX IF NOT EXISTS idx_snapshot_analyzed_at ON architecture_snapshots(analyzed_at);

-- 4. Architecture Nodes
CREATE TABLE IF NOT EXISTS architecture_nodes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id BIGINT NOT NULL,
    node_key VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    node_type VARCHAR(255) NOT NULL,
    file_path VARCHAR(255),
    package_or_module VARCHAR(255),
    annotations_json TEXT,
    start_line INT,
    end_line INT,
    evidence_confidence VARCHAR(255),
    level INT,
    CONSTRAINT fk_node_snapshot FOREIGN KEY (snapshot_id) REFERENCES architecture_snapshots(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_node_snapshot ON architecture_nodes(snapshot_id);
CREATE INDEX IF NOT EXISTS idx_node_key ON architecture_nodes(node_key);

-- 5. Architecture Edges
CREATE TABLE IF NOT EXISTS architecture_edges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id BIGINT NOT NULL,
    source_node_key VARCHAR(255) NOT NULL,
    target_node_key VARCHAR(255) NOT NULL,
    relationship_type VARCHAR(255) NOT NULL,
    evidence TEXT,
    evidence_level VARCHAR(255),
    CONSTRAINT fk_edge_snapshot FOREIGN KEY (snapshot_id) REFERENCES architecture_snapshots(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_edge_snapshot ON architecture_edges(snapshot_id);
CREATE INDEX IF NOT EXISTS idx_edge_source ON architecture_edges(source_node_key);
CREATE INDEX IF NOT EXISTS idx_edge_target ON architecture_edges(target_node_key);

-- 6. City Layouts
CREATE TABLE IF NOT EXISTS city_layouts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id BIGINT NOT NULL UNIQUE,
    layout_algorithm VARCHAR(255) NOT NULL,
    city_width DOUBLE PRECISION,
    city_height DOUBLE PRECISION,
    districts_json TEXT,
    buildings_json TEXT,
    roads_json TEXT,
    calculated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
    CONSTRAINT fk_layout_snapshot FOREIGN KEY (snapshot_id) REFERENCES architecture_snapshots(id) ON DELETE CASCADE
);

-- 7. Code Endpoints
CREATE TABLE IF NOT EXISTS code_endpoints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL,
    snapshot_id BIGINT NOT NULL,
    http_method VARCHAR(16) NOT NULL,
    route_path VARCHAR(512) NOT NULL,
    controller_class VARCHAR(255) NOT NULL,
    handler_method VARCHAR(255) NOT NULL,
    parameters_json TEXT,
    request_body_type VARCHAR(255),
    response_type VARCHAR(255),
    source_file VARCHAR(255),
    start_line INT,
    end_line INT,
    node_key VARCHAR(255),
    api_category VARCHAR(32) DEFAULT 'REST',
    auth_classification VARCHAR(32) DEFAULT 'AUTHENTICATED',
    analysis_status VARCHAR(32) DEFAULT 'COMPLETE',
    discovered_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
    CONSTRAINT fk_endpoint_repo FOREIGN KEY (repository_id) REFERENCES repositories(id) ON DELETE CASCADE,
    CONSTRAINT fk_endpoint_snapshot FOREIGN KEY (snapshot_id) REFERENCES architecture_snapshots(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_endpoint_repo ON code_endpoints(repository_id);
CREATE INDEX IF NOT EXISTS idx_endpoint_snapshot ON code_endpoints(snapshot_id);
CREATE INDEX IF NOT EXISTS idx_endpoint_route ON code_endpoints(route_path);

-- 8. Static Execution Paths
CREATE TABLE IF NOT EXISTS static_execution_paths (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint_id BIGINT NOT NULL,
    snapshot_id BIGINT NOT NULL,
    total_steps INT,
    inferred_summary TEXT,
    has_alternative_branches BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
    CONSTRAINT fk_execpath_endpoint FOREIGN KEY (endpoint_id) REFERENCES code_endpoints(id) ON DELETE CASCADE,
    CONSTRAINT fk_execpath_snapshot FOREIGN KEY (snapshot_id) REFERENCES architecture_snapshots(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_execpath_endpoint ON static_execution_paths(endpoint_id);
CREATE INDEX IF NOT EXISTS idx_execpath_snapshot ON static_execution_paths(snapshot_id);

-- 9. Static Execution Steps
CREATE TABLE IF NOT EXISTS static_execution_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path_id BIGINT NOT NULL,
    step_index INT NOT NULL,
    source_component_key VARCHAR(255) NOT NULL,
    source_component_name VARCHAR(255) NOT NULL,
    target_component_key VARCHAR(255),
    target_component_name VARCHAR(255),
    source_method VARCHAR(255),
    target_method VARCHAR(255),
    call_expression TEXT,
    source_line_number INT,
    relationship_type VARCHAR(255) NOT NULL,
    branch_condition VARCHAR(255),
    evidence TEXT,
    is_resolved BOOLEAN DEFAULT TRUE,
    CONSTRAINT fk_step_path FOREIGN KEY (path_id) REFERENCES static_execution_paths(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_step_path ON static_execution_steps(path_id);
CREATE INDEX IF NOT EXISTS idx_step_order ON static_execution_steps(path_id, step_index);

-- 10. Runtime Traces
CREATE TABLE IF NOT EXISTS runtime_traces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trace_id VARCHAR(64) NOT NULL UNIQUE,
    repository_id BIGINT NOT NULL,
    commit_sha VARCHAR(255),
    endpoint_route VARCHAR(255),
    http_method VARCHAR(255),
    status_code INT,
    duration_ms BIGINT,
    service_name VARCHAR(255),
    recorded_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
    environment VARCHAR(255) DEFAULT 'local-agent',
    CONSTRAINT fk_trace_repo FOREIGN KEY (repository_id) REFERENCES repositories(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_trace_repo ON runtime_traces(repository_id);

-- 11. Runtime Spans
CREATE TABLE IF NOT EXISTS runtime_spans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trace_id BIGINT NOT NULL,
    span_id VARCHAR(64) NOT NULL,
    parent_span_id VARCHAR(255),
    component_key VARCHAR(255),
    component_name VARCHAR(255) NOT NULL,
    operation_name VARCHAR(255) NOT NULL,
    duration_ms BIGINT,
    start_offset_ms BIGINT,
    has_error BOOLEAN DEFAULT FALSE,
    error_message VARCHAR(255),
    attributes_json TEXT,
    CONSTRAINT fk_span_trace FOREIGN KEY (trace_id) REFERENCES runtime_traces(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_span_trace ON runtime_spans(trace_id);
CREATE INDEX IF NOT EXISTS idx_span_spanid ON runtime_spans(span_id);

